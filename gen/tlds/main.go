// Command tlds regenerates ioc/tlds.go from IANA's authoritative TLD list.
//
// It downloads https://data.iana.org/TLD/tlds-alpha-by-domain.txt, lowercases every
// entry, and adds "onion" (a special-use TLD that IANA does not list but which shows
// up in threat reporting). The result is sorted longest-first so the Domain regex's
// TLD alternation prefers the most specific match.
//
// Run with `go generate ./ioc/...` or directly from the ioc/ directory.
package main

import (
	"bufio"
	"fmt"
	"net/http"
	"os"
	"sort"
	"strings"
	"time"
)

const (
	source  = "https://data.iana.org/TLD/tlds-alpha-by-domain.txt"
	outPath = "tlds.go"
)

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, "gen/tlds:", err)
		os.Exit(1)
	}
}

func run() error {
	client := &http.Client{Timeout: 30 * time.Second}
	resp, err := client.Get(source)
	if err != nil {
		return err
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		return fmt.Errorf("unexpected status %d fetching %s", resp.StatusCode, source)
	}

	set := map[string]struct{}{}
	scanner := bufio.NewScanner(resp.Body)
	for scanner.Scan() {
		line := strings.TrimSpace(scanner.Text())
		if line == "" || strings.HasPrefix(line, "#") {
			continue // skip the comment header line
		}
		// Skip internationalized (punycode) TLDs like "xn--..."; the Domain regex's
		// label class is ASCII only so they could never match anyway.
		if strings.HasPrefix(strings.ToLower(line), "xn--") {
			continue
		}
		set[strings.ToLower(line)] = struct{}{}
	}
	if err := scanner.Err(); err != nil {
		return err
	}

	// onion is omitted by IANA but is a meaningful IOC.
	set["onion"] = struct{}{}

	tlds := make([]string, 0, len(set))
	for t := range set {
		tlds = append(tlds, t)
	}
	// Longest-first (then alphabetical) so the regex alternation prefers the most
	// specific TLD (e.g. "community" before "com").
	sort.Slice(tlds, func(i, j int) bool {
		if len(tlds[i]) != len(tlds[j]) {
			return len(tlds[i]) > len(tlds[j])
		}
		return tlds[i] < tlds[j]
	})

	var b strings.Builder
	b.WriteString("// Code generated by gen/tlds; DO NOT EDIT.\n")
	b.WriteString("// Source: " + source + "\n")
	b.WriteString("// Regenerate with: go generate ./ioc/...\n\n")
	b.WriteString("package ioc\n\n")
	fmt.Fprintf(&b, "// tlds is the IANA TLD list (%d entries) plus \"onion\", used to build the Domain regex.\n", len(tlds))
	b.WriteString("var tlds = []string{\n")
	for _, t := range tlds {
		fmt.Fprintf(&b, "\t%q,\n", t)
	}
	b.WriteString("}\n")

	return os.WriteFile(outPath, []byte(b.String()), 0o644)
}
